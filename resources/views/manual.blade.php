    <h1>Manual de usuario</h1>
    <p>Cómo participar en una subasta paso a paso.</p>
    <ol>
        <li><strong>Cree su cuenta.</strong> La cuenta registrada puede participar en todas las etapas del proceso.</li>
        <li><strong>Inscríbase</strong> al bien de su interés dentro del horario de inscripciones. Fuera de ese horario no es posible inscribirse.</li>
        <li><strong>Suba su voucher de pago.</strong> Es obligatorio: sin este documento no se puede aprobar su inscripción.</li>
        <li><strong>Espere la aprobación</strong> del organizador. Recibirá un correo confirmando la recepción de su inscripción.</li>
        <li><strong>Ingrese a la subasta</strong> antes de la hora de inicio.</li>
        <li><strong>Realice sus pujas.</strong> Al finalizar, la plataforma muestra al ganador.</li>
    </ol>
    <p class="aviso">Una vez iniciada la subasta no se permite el ingreso de nuevos participantes.</p>
